#!/usr/bin/env node
// One codebase, several apps. www/ and native/ are written once, as the source brand (Zain Life);
// each brand in brands/<id>/brand.json says how its app differs: name, app id, backup folder, icon
// mark, colours (www/brand/<id>/theme.css), Android icons (brands/<id>/android/res) and which
// features it leaves out. Every build turns the source into the brand's app, so a change made once
// lands in every app.
//
//   node tools/brand.js web <id> <outDir>   write the brand's web app (www/ transformed) to outDir
//   node tools/brand.js android <id>        after `npx cap sync android`: brand the copied web app,
//                                           capacitor.config.json and the Android flavor folder
//   node tools/brand.js check [id]          build each brand into a temp folder and check for leaks
//
// Leak check: a brand's "marks" (e.g. "zain", "زين" and the swirl logo's path) must not appear
// anywhere in another brand's app. If a new screen says "Zain HR", the personal build stops and
// names the file and line, so nothing Zain-only slips into the personal app by accident.
'use strict';
const fs = require('fs'), path = require('path'), os = require('os');

const ROOT = path.join(__dirname, '..');
const WWW = path.join(ROOT, 'www');
const BRANDS = path.join(ROOT, 'brands');
const TEXT = /\.(html|js|css|json|svg|xml|txt|md)$/i;
const AR = '\\u0600-\\u06FF';

function ids() {
  return fs.readdirSync(BRANDS).filter(d => fs.existsSync(path.join(BRANDS, d, 'brand.json'))).sort();
}
function load(id) {
  const f = path.join(BRANDS, id, 'brand.json');
  if (!fs.existsSync(f)) throw new Error(`No brand "${id}". Brands: ${ids().join(', ')}`);
  return JSON.parse(fs.readFileSync(f, 'utf8'));
}
function source() {
  const s = ids().map(load).filter(b => b.source);
  if (s.length !== 1) throw new Error('Exactly one brand must have "source": true');
  return s[0];
}

const escRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const isAr = s => new RegExp(`[${AR}]`).test(s);
// Whole words only: Arabic "زين" must not hit "تخزين" (storage); "Zain" must not hit a longer word.
function wordRe(s, flags) {
  return isAr(s) ? new RegExp(`(?<![${AR}])${escRe(s)}(?![${AR}])`, flags)
                 : new RegExp(`(?<![A-Za-z])${escRe(s)}(?![A-Za-z])`, flags);
}

// Ordered replacements that turn source-brand text into the target brand's. Longest first.
function pairs(src, dst) {
  if (src.id === dst.id) return [];
  return [
    [src.mark, dst.mark, false],
    [`brand/${src.id}/`, `brand/${dst.id}/`, false],
    [src.appId, dst.appId, false],
    [src.name, dst.name, true],
    [src.nameAr, dst.nameAr, true],
    [src.folder, dst.folder, false],
    [src.short, dst.short, true],
    [src.shortAr, dst.shortAr, true]
  ].filter(p => p[0] && p[1] !== undefined);
}
function swap(text, list) {
  for (const [from, to, word] of list) text = word ? text.replace(wordRe(from, 'g'), () => to) : text.split(from).join(to);
  return text;
}

function brandJs(b) {
  const pub = { id: b.id, name: b.name, nameAr: b.nameAr, folder: b.folder, features: b.features || {} };
  return '/* Generated by tools/brand.js from brands/' + b.id + '/brand.json. */\n' +
    'window.BRAND = ' + JSON.stringify(pub) + ';\n' +
    "document.documentElement.setAttribute('data-brand', window.BRAND.id);\n";
}

// One www/ file for brand b: new text, or null when the brand leaves the file out.
function transformFile(rel, buf, b, src) {
  rel = rel.split(path.sep).join('/');
  const drop = new Set(b.drop || []);
  if (drop.has(rel)) return null;
  const m = /^brand\/([^/]+)\//.exec(rel);
  if (m && m[1] !== b.id) return null;                       // other brands' logos and colours
  if (rel === 'brand.js') return Buffer.from(brandJs(b));
  if (!TEXT.test(rel)) return buf;
  let t = buf.toString('utf8');
  if (/\.html$/i.test(rel)) {
    for (const f of drop) t = t.replace(new RegExp(`[ \\t]*<script src="${escRe(f)}"></script>\\r?\\n?`, 'g'), '');
  }
  return Buffer.from(swap(t, pairs(src, b)));
}

function walk(dir, base = dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, base, out); else out.push(path.relative(base, p));
  }
  return out;
}

function buildWeb(id, outDir) {
  const b = load(id), src = source();
  fs.rmSync(outDir, { recursive: true, force: true });
  let n = 0;
  for (const rel of walk(WWW)) {
    const data = transformFile(rel, fs.readFileSync(path.join(WWW, rel)), b, src);
    if (data === null) continue;
    const to = path.join(outDir, rel);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, data); n++;
  }
  return n;
}

// Every place a mark of another brand shows up in the given files/folders.
function leaks(id, roots) {
  const others = ids().filter(x => x !== id).map(load);
  const res = others.flatMap(o => (o.marks || []).map(mk => ({ mk, re: isAr(mk) ? wordRe(mk, '') : new RegExp(escRe(mk), 'i') })));
  const found = [];
  for (const r of roots) {
    if (!fs.existsSync(r)) continue;
    const files = fs.statSync(r).isDirectory() ? walk(r).map(f => path.join(r, f)) : [r];
    for (const f of files) {
      if (!TEXT.test(f) && !/\.(java|kt|gradle|properties)$/i.test(f)) continue;
      fs.readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
        for (const { mk, re } of res) if (re.test(line)) found.push(`${path.relative(ROOT, f)}:${i + 1}  "${mk}"  ${line.trim().slice(0, 120)}`);
      });
    }
  }
  return found;
}
function report(id, found) {
  if (!found.length) return true;
  console.error(`\nThe ${load(id).name} app still has text from another brand (${found.length} place(s)):`);
  found.slice(0, 40).forEach(l => console.error('  ' + l));
  console.error('\nUse the brand name (it is swapped in automatically), or give the feature a "features" switch /' +
    ' "drop" entry in brands/<id>/brand.json so it stays in its own brand.');
  return false;
}

function copyDir(from, to) {
  if (!fs.existsSync(from)) return;
  for (const rel of walk(from)) {
    fs.mkdirSync(path.dirname(path.join(to, rel)), { recursive: true });
    fs.copyFileSync(path.join(from, rel), path.join(to, rel));
  }
}

// android/app/src/<id>: the brand's icons, colours, names and manifest changes, rebuilt from brands/<id>/android.
function writeFlavor(id) {
  const b = load(id);
  const flavor = path.join(ROOT, 'android', 'app', 'src', id);
  fs.rmSync(flavor, { recursive: true, force: true });
  copyDir(path.join(BRANDS, id, 'android'), flavor);
  const vals = path.join(flavor, 'res', 'values');
  fs.mkdirSync(vals, { recursive: true });
  const x = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/'/g, "\\'");
  fs.writeFileSync(path.join(vals, 'brand.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand.js from brands/${id}/brand.json. Edit that file, not this one. -->
<resources>
    <string name="app_name">${x(b.name)}</string>
    <string name="title_activity_main">${x(b.name)}</string>
    <string name="package_name">${b.appId}</string>
    <string name="custom_url_scheme">${b.appId}</string>
    <string name="brand_folder">${x(b.folder)}</string>
    <color name="ic_launcher_background">${b.iconBackground}</color>
</resources>
`);
  return flavor;
}

// After `npx cap sync android`: brand the copied web app and its config, write the flavor folder,
// then check everything that goes into this brand's APK for another brand's text.
function android(id) {
  const b = load(id);
  const app = path.join(ROOT, 'android', 'app', 'src');
  const pub = path.join(app, 'main', 'assets', 'public');
  buildWeb(id, pub);
  const cfgFile = path.join(app, 'main', 'assets', 'capacitor.config.json');
  const cfg = JSON.parse(fs.readFileSync(cfgFile, 'utf8'));
  cfg.appId = b.appId; cfg.appName = b.name;
  cfg.android = Object.assign({}, cfg.android, { backgroundColor: b.background });
  fs.writeFileSync(cfgFile, JSON.stringify(cfg, null, '\t') + '\n');
  const flavor = writeFlavor(id);
  const found = leaks(id, [pub, cfgFile, flavor, path.join(app, 'main', 'res'), path.join(app, 'main', 'java'), path.join(app, 'main', 'AndroidManifest.xml')]);
  if (!report(id, found)) process.exit(1);
  console.log(`     ${b.name}: web app, config and android/app/src/${id} ready (${b.appId}).`);
}

function check(only) {
  let ok = true;
  for (const id of only ? [only] : ids()) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'brand-' + id + '-'));
    const n = buildWeb(id, dir);
    const found = leaks(id, [dir, path.join(BRANDS, id)]);
    if (report(id, found)) console.log(`ok  ${load(id).name}: ${n} files, no other-brand text`); else ok = false;
    fs.rmSync(dir, { recursive: true, force: true });
  }
  return ok;
}

module.exports = { ids, load, source, transformFile, buildWeb, leaks, brandJs, writeFlavor };

if (require.main === module) {
  const [cmd, id, out] = process.argv.slice(2);
  try {
    if (cmd === 'web' && id && out) console.log(`${buildWeb(id, path.resolve(out))} files written to ${out}`);
    else if (cmd === 'android' && id) android(id);
    else if (cmd === 'check') process.exit(check(id) ? 0 : 1);
    else { console.log('Usage: node tools/brand.js web <id> <outDir> | android <id> | check [id]'); process.exit(2); }
  } catch (e) { console.error(e.message); process.exit(1); }
}
